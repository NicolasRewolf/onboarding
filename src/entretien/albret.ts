function tarifPreview(all: Answers): string | null {
  const t = all["tarif-taux"];
  if (!t || !num(t)) return null;
  const base = all["tarif-base"]?.value;
  const sur = base === "cc" ? " des loyers encaissés, charges comprises" : base === "hc" ? " des loyers encaissés, hors charges" : "";
  return `Honoraires de gestion : ${num(t)} % ${t.qualifier === "ht" ? "HT" : "TTC"}${sur}.`;
}

